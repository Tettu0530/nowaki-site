#!/usr/bin/env node
// Copies the framework docs from Tettu0530/nowaki at a tag or commit into content/docs/, so
// nowaki.dev shows the upstream Markdown as is (rendered by Nowaki's own content collections).
//
//   node scripts/sync-docs.mjs v1.0.0-rc.1
//
// Never hand-edit content/docs/: change the docs upstream and sync again. This script only
// adds frontmatter (title, source path), drops the leading "# Title" (the page renders it),
// and rewrites links: links between synced pages become nowaki.dev URLs, links to other repo
// files (CHANGELOG.md, examples/, SECURITY.md) point at GitHub at the same ref.
import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, posix } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = "Tettu0530/nowaki";
const ref = process.argv[2];
if (!ref) {
  console.error("usage: node scripts/sync-docs.mjs <tag-or-commit>");
  process.exit(1);
}
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "content/docs");

// Upstream path (under the repo root) → nowaki.dev slug under /docs/. Order is the sidebar order
// inside each group (see lib/docs-nav.ts).
function slugFor(path) {
  if (!path.startsWith("docs/") || !path.endsWith(".md")) return null;
  const p = path.slice("docs/".length, -".md".length);
  if (p === "README" || p === "RELEASING") return null; // the site's own overview; maintainers only
  if (p === "STABILITY") return "stability";
  if (p.endsWith("/README")) return p.slice(0, -"/README".length); // deploy, reference
  return p;
}

const work = mkdtempSync(join(tmpdir(), "nowaki-docs-"));
try {
  const tgz = join(work, "src.tgz");
  const res = await fetch(`https://codeload.github.com/${REPO}/tar.gz/${encodeURIComponent(ref)}`);
  if (!res.ok) throw new Error(`download ${ref}: HTTP ${res.status}`);
  writeFileSync(tgz, Buffer.from(await res.arrayBuffer()));
  execFileSync("tar", ["-xzf", tgz, "-C", work]);
  const top = readdirSync(work).find((n) => n !== "src.tgz");
  const repoRoot = join(work, top);
  const shaRes = await fetch(`https://api.github.com/repos/${REPO}/commits/${encodeURIComponent(ref)}`, {
    headers: { accept: "application/vnd.github.sha" },
  });
  if (!shaRes.ok) throw new Error(`resolve ${ref}: HTTP ${shaRes.status}`);
  const commit = (await shaRes.text()).trim();

  const files = [];
  const walk = (dir) => {
    for (const n of readdirSync(join(repoRoot, dir))) {
      const rel = posix.join(dir, n);
      if (statSync(join(repoRoot, rel)).isDirectory()) walk(rel);
      else if (slugFor(rel)) files.push(rel);
    }
  };
  walk("docs");

  const gh = (path, isDir) => `https://github.com/${REPO}/${isDir ? "tree" : "blob"}/${ref}/${path}`;
  const link = (fromPath, target) => {
    if (/^([a-z]+:|#|\/)/i.test(target)) return target; // absolute, anchor-only, or root-relative
    const [p, hash = ""] = target.split("#");
    const resolved = posix.normalize(posix.join(posix.dirname(fromPath), p)).replace(/\/$/, "");
    const h = hash ? `#${hash}` : "";
    if (resolved === "docs/README.md" || resolved === "docs") return `/docs/${h}`;
    const slug = slugFor(resolved);
    if (slug) return `/docs/${slug}/${h}`;
    const isDir = !posix.basename(resolved).includes(".");
    return gh(resolved, isDir) + (hash ? `#${hash}` : "");
  };

  // Rewrite inline links outside code: fenced blocks and `code spans` are left alone.
  const rewrite = (fromPath, md) => {
    const lines = md.split("\n");
    let fence = null;
    return lines
      .map((line) => {
        const m = line.match(/^\s*(`{3,}|~{3,})/);
        if (m) {
          if (!fence) fence = m[1][0].repeat(m[1].length);
          else if (line.trim().startsWith(fence)) fence = null;
          return line;
        }
        if (fence) return line;
        return line
          .split(/(`+[^`]*`+)/)
          .map((part, i) => (i % 2 ? part : part.replace(/\]\(([^)\s]+)((?:\s+"[^"]*")?)\)/g, (_, t, title) => `](${link(fromPath, t)}${title})`)))
          .join("");
      })
      .join("\n");
  };

  rmSync(out, { recursive: true, force: true });
  const pages = [];
  for (const rel of files.sort()) {
    const slug = slugFor(rel);
    let md = readFileSync(join(repoRoot, rel), "utf8").replace(/\r\n/g, "\n");
    // Generated reference pages start with a "Generated by scripts/gen-reference.mjs" comment.
    const generated = /^<!--[^]*?gen-reference/.test(md);
    md = md.replace(/^(?:<!--[^]*?-->\s*)+/, "");
    const h1 = md.match(/^# (.+)\n/);
    if (!h1) throw new Error(`${rel}: no leading "# Title"`);
    const title = h1[1].trim();
    md = md.slice(h1[0].length).replace(/^\n+/, "");
    md = rewrite(rel, md);
    const front = `---\ntitle: ${JSON.stringify(title)}\nsource: ${JSON.stringify(rel)}\ngenerated: ${generated}\n---\n\n`;
    const dest = join(out, `${slug}.md`);
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, front + md);
    pages.push({ slug, title, source: rel, generated });
  }
  writeFileSync(
    join(root, "lib/docs-source.json"),
    JSON.stringify({ repo: REPO, ref, commit, pages }, null, 2) + "\n",
  );
  console.log(`synced ${pages.length} pages from ${REPO}@${ref} (${commit}) into content/docs/`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
